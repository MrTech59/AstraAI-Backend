"""Configuration templates and provider metadata for the Astra installer."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class ProviderInfo:
    """Static metadata for a provider selectable during setup."""

    key: str
    display_name: str
    api_key_var: str
    base_url: str
    default_model: str
    key_required: bool = True
    supports_custom_model: bool = True



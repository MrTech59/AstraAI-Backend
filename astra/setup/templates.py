# Map user-facing aliases to canonical keys.
PROVIDER_ALIASES = {
    "nvidia": "nvidia_build",
    "openai": "openai-compatible",
    "openai_compatible": "openai-compatible",
}


def resolve_provider_key(name: str) -> str:
    """Normalize a provider name to its canonical setup key."""
    key = name.lower()
    key = PROVIDER_ALIASES.get(key, key)
    if key not in PROVIDERS:
        raise ValueError(f"Unknown provider: {name!r}")
    return key


def get_provider_info(name: str) -> ProviderInfo:
    """Return metadata for a provider name or alias."""
    return PROVIDERS[resolve_provider_key(name)]


def get_sorted_providers() -> list[ProviderInfo]:
    """Return providers in a stable, sensible order."""
    order = ["openrouter", "nvidia_build", "ollama", "openai-compatible"]
    return [get_provider_info(k) for k in order]


def _toml_value(value: object) -> str:
    """Format a Python value as valid TOML."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        if not value:
            return "[]"
        items = ", ".join(_toml_value(item) for item in value)
        return f"[{items}]"
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        return f'"{escaped}"'
    raise TypeError(f"Unsupported TOML value type: {type(value).__name__}")


# TOML template rendered with ``str.format``.  Secrets must NOT appear here.
CONFIG_TEMPLATE = """# Astra Core configuration
# Generated by `astra setup` on {timestamp}
# Do NOT put API keys here — use environment variables or `.env`

[llm]
provider = {provider}
model = {model}
base_url = {base_url}
temperature = {temperature}
max_tokens = {max_tokens}
timeout = {timeout}

[agent]
system_prompt = {system_prompt}
max_tool_iterations = {max_tool_iterations}

[context]
max_messages = {max_messages}
max_memories = {max_memories}

[memory]
db_path = {db_path}

[security]
allow_shell = {allow_shell}
allowed_shell_prefixes = {allowed_shell_prefixes}
filesystem_roots = {filesystem_roots}

[api]
host = {host}
port = {port}

[logging]
level = {level}
file = {log_file}

[permissions]
filesystem_list = {filesystem_list}
filesystem_read = {filesystem_read}
filesystem_write = {filesystem_write}
shell_exec = {shell_exec}
""".lstrip()

ENV_TEMPLATE = """# Astra Core environment secrets
# Generated by `astra setup`
# This file is ignored by git. Do not commit it.

{api_key_line}
""".lstrip()


def render_config(context: dict[str, object]) -> str:
    """Render ``config.toml`` from collected setup answers."""
    formatted = {key: _toml_value(value) for key, value in context.items()}
    return CONFIG_TEMPLATE.format(**formatted)


def render_env(api_key_var: str, api_key_value: str) -> str:
    """Render ``.env`` with one secret key."""
    line = f"{api_key_var}={api_key_value}" if api_key_value.strip() else ""
    return ENV_TEMPLATE.format(api_key_line=line).rstrip() + "\n"

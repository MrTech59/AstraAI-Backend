#!/usr/bin/env python3
"""Interactive Astra backend configuration wizard.

Prompts for provider, model, API key, and server bind settings, then writes
config/config.toml and .env so the user does not have to edit files by hand.
"""

from __future__ import annotations

import getpass
import os
import sys
from pathlib import Path


CONFIG_PATH = Path("config/config.toml")
ENV_PATH = Path(".env")
CONFIG_EXAMPLE = Path("config/config.example.toml")
ENV_EXAMPLE = Path(".env.example")

PROVIDERS = {
    "1": ("openrouter", "openrouter/free", "https://openrouter.ai/api/v1", "OPENROUTER_API_KEY"),
    "2": ("nvidia_build", "z-ai/glm-5.3-flash", "https://integrate.api.nvidia.com/v1", "NVIDIA_API_KEY"),
    "3": ("ollama", "qwen3", "http://localhost:11434/v1", "OLLAMA_API_KEY"),
    "4": ("openai-compatible", "gpt-4o-mini", "https://api.openai.com/v1", "OPENAI_API_KEY"),
}


def prompt(text: str, default: str = "") -> str:
    if default:
        user = input(f"{text} [{default}]: ").strip()
    else:
        user = input(f"{text}: ").strip()
    return user if user else default


def prompt_key(text: str) -> str:
    """Prompt for a secret, allowing empty input."""
    try:
        value = getpass.getpass(f"{text}: ")
    except EOFError:
        value = ""
    return value


def write_env(api_key_name: str, api_key_value: str) -> None:
    lines = []
    if ENV_EXAMPLE.exists():
        lines = ENV_EXAMPLE.read_text(encoding="utf-8").splitlines()
    else:
        lines = [
            "# Astra Core environment secrets",
            "# Do not commit this file.",
            "",
            "OPENROUTER_API_KEY=",
            "NVIDIA_API_KEY=",
            "OLLAMA_API_KEY=",
        ]

    prefix = api_key_name + "="
    updated = []
    found = False
    for line in lines:
        if line.startswith(prefix):
            updated.append(prefix + api_key_value)
            found = True
        else:
            updated.append(line)
    if not found:
        updated.append(prefix + api_key_value)

    ENV_PATH.write_text("\n".join(updated) + "\n", encoding="utf-8")


def write_config(provider: str, model: str, base_url: str, host: str, port: int) -> None:
    template = """# Astra Core configuration
# Generated by scripts/configure.py
# Do NOT put API keys here — use environment variables or .env

[llm]
provider = "{provider}"
model = "{model}"
base_url = "{base_url}"
temperature = 0.7
max_tokens = 2048
timeout = 60.0

[agent]
system_prompt = "You are Astra, a helpful AI assistant with access to tools. Use tools when they help answer the user. Be concise."
max_tool_iterations = 8

[context]
max_messages = 30
max_memories = 5

[memory]
db_path = "data/astra.db"

[security]
allow_shell = false
allowed_shell_prefixes = ["echo ", "ls ", "cat ", "python " ]
filesystem_roots = ["."]

[api]
host = "{host}"
port = {port}

[logging]
level = "INFO"
file = "logs/astra.log"

[permissions]
filesystem_list = "allow"
filesystem_read = "allow"
filesystem_write = "confirm"
shell_exec = "confirm"
"""
    CONFIG_PATH.write_text(template.format(
        provider=provider,
        model=model,
        base_url=base_url,
        host=host,
        port=port,
    ), encoding="utf-8")


def main() -> int:
    print("Astra Backend Configuration")
    print("=" * 40)
    print()
    print("Choose an LLM provider:")
    print("  1) OpenRouter")
    print("  2) NVIDIA Build")
    print("  3) Ollama (local)")
    print("  4) OpenAI-compatible")
    print()

    choice = prompt("Provider number", "1")
    if choice not in PROVIDERS:
        print(f"Invalid choice: {choice}", file=sys.stderr)
        return 1

    provider, default_model, default_base_url, key_name = PROVIDERS[choice]

    model = prompt("Model", default_model)
    base_url = prompt("Base URL", default_base_url)
    api_key = prompt_key(f"API key ({key_name}; leave blank if not needed)")

    print()
    print("Server bind settings:")
    host = prompt("Host", "127.0.0.1")
    port_str = prompt("Port", "8321")
    try:
        port = int(port_str)
    except ValueError:
        print(f"Invalid port: {port_str}", file=sys.stderr)
        return 1

    print()
    print("Public domain (optional; used for the Flutter app and reverse proxy):")
    domain = prompt("Domain", "")

    CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    write_config(provider, model, base_url, host, port)
    write_env(key_name, api_key)

    if domain:
        caddy = f"""# Caddyfile for {domain}
# Place this file next to Caddy's main config, or run:
#   caddy reverse-proxy --from {domain} --to {host}:{port}
{domain} {{
    reverse_proxy {host}:{port}
}}
"""
        Path("Caddyfile").write_text(caddy, encoding="utf-8")

    print()
    print("Configuration written:")
    print(f"  - {CONFIG_PATH}")
    print(f"  - {ENV_PATH}")
    if domain:
        print(f"  - Caddyfile")
    print()
    print("Start the server:")
    print("  source .venv/bin/activate")
    print("  python api/server.py")
    print()
    if domain:
        print(f"Reverse proxy (Caddy):")
        print(f"  {domain} {{")
        print(f"      reverse_proxy {host}:{port}")
        print(f"  }}")
        print()
        print(f"Run the Flutter app:")
        print(f"  flutter run --dart-define=ASTRA_BACKEND_URL=wss://{domain}")
    else:
        print("Run the Flutter app locally:")
        print(f"  flutter run --dart-define=ASTRA_BACKEND_URL=ws://{host}:{port}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\nCancelled.", file=sys.stderr)
        sys.exit(130)

#!/usr/bin/env python3
"""Interactive Astra backend configuration wizard.

Prompts for provider, model, API key, and server bind settings, then writes
config/config.toml and .env so the user does not have to edit files by hand.
"""

from __future__ import annotations

import getpass
import os
import sys
from pathlib import Path


CONFIG_PATH = Path("config/config.toml")
ENV_PATH = Path(".env")
CONFIG_EXAMPLE = Path("config/config.example.toml")
ENV_EXAMPLE = Path(".env.example")

PROVIDERS = {
    "1": ("openrouter", "openrouter/free", "https://openrouter.ai/api/v1", "OPENROUTER_API_KEY"),
    "2": ("nvidia_build", "z-ai/glm-5.3-flash", "https://integrate.api.nvidia.com/v1", "NVIDIA_API_KEY"),
    "3": ("ollama", "qwen3", "http://localhost:11434/v1", "OLLAMA_API_KEY"),
    "4": ("openai-compatible", "gpt-4o-mini", "https://api.openai.com/v1", "OPENAI_API_KEY"),
}


def prompt(text: str, default: str = "") -> str:
    if default:
        user = input(f"{text} [{default}]: ").strip()
    else:
        user = input(f"{text}: ").strip()
    return user if user else default


def prompt_key(text: str) -> str:
    """Prompt for a secret, allowing empty input."""
    try:
        value = getpass.getpass(f"{text}: ")
    except EOFError:
        value = ""
    return value


def write_env(api_key_name: str, api_key_value: str) -> None:
    lines = []
    if ENV_EXAMPLE.exists():
        lines = ENV_EXAMPLE.read_text(encoding="utf-8").splitlines()
    else:
        lines = [
            "# Astra Core environment secrets",
            "# Do not commit this file.",
            "",
            "OPENROUTER_API_KEY=",
            "NVIDIA_API_KEY=",
            "OLLAMA_API_KEY=",
        ]

    prefix = api_key_name + "="
    updated = []
    found = False
    for line in lines:
        if line.startswith(prefix):
            updated.append(prefix + api_key_value)
            found = True
        else:
            updated.append(line)
    if not found:
        updated.append(prefix + api_key_value)

    ENV_PATH.write_text("\n".join(updated) + "\n", encoding="utf-8")


def write_config(provider: str, model: str, base_url: str, host: str, port: int) -> None:
    template = """# Astra Core configuration
# Generated by scripts/configure.py
# Do NOT put API keys here — use environment variables or .env

[llm]
provider = "{provider}"
model = "{model}"
base_url = "{base_url}"
temperature = 0.7
max_tokens = 2048
timeout = 60.0

[agent]
system_prompt = "You are Astra, a helpful AI assistant with access to tools. Use tools when they help answer the user. Be concise."
max_tool_iterations = 8

[context]
max_messages = 30
max_memories = 5

[memory]
db_path = "data/astra.db"

[security]
allow_shell = false
allowed_shell_prefixes = ["echo ", "ls ", "cat ", "python " ]
filesystem_roots = ["."]

[api]
host = "{host}"
port = {port}

[logging]
level = "INFO"
file = "logs/astra.log"

[permissions]
filesystem_list = "allow"
filesystem_read = "allow"
filesystem_write = "confirm"
shell_exec = "confirm"
"""
    CONFIG_PATH.write_text(template.format(
        provider=provider,
        model=model,
        base_url=base_url,
        host=host,
        port=port,
    ), encoding="utf-8")


def main() -> int:
    print("Astra Backend Configuration")
    print("=" * 40)
    print()
    print("Choose an LLM provider:")
    print("  1) OpenRouter")
    print("  2) NVIDIA Build")
    print("  3) Ollama (local)")
    print("  4) OpenAI-compatible")
    print()

    choice = prompt("Provider number", "1")
    if choice not in PROVIDERS:
        print(f"Invalid choice: {choice}", file=sys.stderr)
        return 1

    provider, default_model, default_base_url, key_name = PROVIDERS[choice]

    model = prompt("Model", default_model)
    base_url = prompt("Base URL", default_base_url)
    api_key = prompt_key(f"API key ({key_name}; leave blank if not needed)")

    print()
    print("Server bind settings:")
    host = prompt("Host", "127.0.0.1")
    port_str = prompt("Port", "8321")
    try:
        port = int(port_str)
    except ValueError:
        print(f"Invalid port: {port_str}", file=sys.stderr)
        return 1

    print()
    print("Public domain (optional; used by the Flutter app):")
    domain = prompt("Domain", "").strip()
    # Strip protocol and trailing slashes so "https://example.com/" becomes "example.com"
    domain = domain.removeprefix("https://").removeprefix("http://").removesuffix("/")

    tunnel_type = "none"
    tunnel_id = ""
    if domain:
        print()
        print("How will you expose the backend to that domain?")
        print("  1) Caddy")
        print("  2) Cloudflare Tunnel (cloudflared)")
        print("  3) Nginx")
        print("  4) Something else / already set up")
        tunnel_choice = prompt("Tunnel number", "2")
        tunnel_map = {"1": "caddy", "2": "cloudflare", "3": "nginx", "4": "none"}
        tunnel_type = tunnel_map.get(tunnel_choice, "none")

        if tunnel_type == "cloudflare":
            print()
            print("If you already created a Cloudflare tunnel, paste its ID here.")
            print("Leave blank to use placeholders and fill them in after running")
            print("  cloudflared tunnel create astra")
            tunnel_id = prompt("Tunnel ID", "").strip()

    CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    write_config(provider, model, base_url, host, port)
    write_env(key_name, api_key)

    generated_files: list[str] = []
    if domain:
        if tunnel_type == "caddy":
            caddy = f"""# Caddyfile for {domain}
# Place this file next to Caddy's main config, or run:
#   caddy reverse-proxy --from {domain} --to {host}:{port}
{domain} {{
    reverse_proxy {host}:{port}
}}
"""
            Path("Caddyfile").write_text(caddy, encoding="utf-8")
            generated_files.append("Caddyfile")
        elif tunnel_type == "cloudflare":
            if tunnel_id:
                creds_file = f"/root/.cloudflared/{tunnel_id}.json"
                placeholder_note = ""
            else:
                tunnel_id = "<TUNNEL_ID>"
                creds_file = "/root/.cloudflared/<TUNNEL_ID>.json"
                placeholder_note = """#
# Replace <TUNNEL_ID> and the credentials-file path with the values from:
#   cloudflared tunnel create astra
"""
            cf_config = f"""# Cloudflare Tunnel config for {domain}{placeholder_note}tunnel: {tunnel_id}
credentials-file: {creds_file}
ingress:
  - hostname: {domain}
    service: http://{host}:{port}
  - service: http_status:404
"""
            Path("cloudflared-config.yml").write_text(cf_config, encoding="utf-8")
            generated_files.append("cloudflared-config.yml")
        elif tunnel_type == "nginx":
            nginx = f"""# Nginx server block for {domain}
server {{
    listen 443 ssl;
    server_name {domain};

    ssl_certificate /path/to/cert.pem;
    ssl_certificate_key /path/to/key.pem;

    location / {{
        proxy_pass http://{host}:{port};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host $host;
    }}
}}
"""
            Path("nginx-server-block.conf").write_text(nginx, encoding="utf-8")
            generated_files.append("nginx-server-block.conf")

    print()
    print("Configuration written:")
    print(f"  - {CONFIG_PATH}")
    print(f"  - {ENV_PATH}")
    for f in generated_files:
        print(f"  - {f}")
    print()
    print("Start the server:")
    print("  source .venv/bin/activate")
    print("  python api/server.py")
    print()
    if domain:
        print(f"Public URL: https://{domain}")
        print()
        if tunnel_type == "caddy":
            print("Run Caddy:")
            print("  caddy run")
        elif tunnel_type == "cloudflare":
            print("Set up Cloudflare Tunnel:")
            print("  cloudflared tunnel login")
            print("  cloudflared tunnel create astra")
            print(f"  cloudflared tunnel route dns astra {domain}")
            print()
            print("After creating the tunnel, update cloudflared-config.yml")
            print("with the tunnel ID and credentials-file path, then run:")
            print("  cloudflared tunnel --config cloudflared-config.yml run astra")
        elif tunnel_type == "nginx":
            print("Copy nginx-server-block.conf into your Nginx sites directory and reload.")
        print()
        print(f"Run the Flutter app:")
        print(f"  flutter run --dart-define=ASTRA_BACKEND_URL=wss://{domain}")
    else:
        print("Run the Flutter app locally:")
        print(f"  flutter run --dart-define=ASTRA_BACKEND_URL=ws://{host}:{port}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\nCancelled.", file=sys.stderr)
        sys.exit(130)
